// Regenerates assets/enzymes.js from the app's own enzyme list, so the website and the app use the same data.
// Usage: node tools/build-enzymes.mjs [path/to/app/src/core/enzymes.ts]   (default: ../plasmidlab/app/src/core/enzymes.ts)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const site = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(process.argv[2] ?? join(site, '..', 'plasmidlab', 'app', 'src', 'core', 'enzymes.ts'))
const ts = readFileSync(source, 'utf8')
const raw = ts.match(/const RAW = `([^`]*)`/)?.[1]
if (!raw) throw new Error('No RAW enzyme list in ' + source)
// The app's ENZYMES parse: "name site cut cut2 suppliers" entries joined by "|".
const enzymes = raw.split('|').map((entry) => {
  const [name, site, cut, cut2] = entry.split(' ')
  if (!name || !/^[ACGTRYSWKMBDHVN]+$/.test(site) || !Number.isInteger(+cut) || !Number.isInteger(+cut2)) throw new Error('Unexpected entry: ' + entry)
  return [name, site, +cut, +cut2]
})
// Entries with their own cut records (enzymes.ts `records`) would need assets/tools.js taught about them.
if (!ts.includes('return { name, site, cut: +cut, cut2: +cut2, suppliers }')) throw new Error('enzymes.ts builds ENZYMES differently now; check this script against it')
const out = `// Generated by tools/build-enzymes.mjs from the PlasmidLab app's enzyme list (app/src/core/enzymes.ts). Do not edit by hand.
// [name, recognition site, top-strand cut, bottom-strand cut], offsets from the start of the site.
// Source: REBASE, the Restriction Enzyme Database (http://rebase.neb.com), release 611.
globalThis.PLASMIDLAB_ENZYMES = ${JSON.stringify(enzymes)};
`
writeFileSync(join(site, 'assets', 'enzymes.js'), out)
console.log(`assets/enzymes.js: ${enzymes.length} enzymes from ${source}`)

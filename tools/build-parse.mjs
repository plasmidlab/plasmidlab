// Regenerates assets/parse.js from the app's own file readers, so the website opens a file exactly as the app does.
// Usage: node tools/build-parse.mjs [path/to/plasmidlab/app]   (default: ../plasmidlab/app)
import { mkdtempSync, writeFileSync, rmSync, readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { tmpdir } from 'node:os'

const site = join(dirname(fileURLToPath(import.meta.url)), '..')
const app = resolve(process.argv[2] ?? join(site, '..', 'plasmidlab', 'app'))
const esbuild = join(app, 'node_modules', '.bin', 'esbuild')
const core = join(app, 'src', 'core')

const work = mkdtempSync(join(tmpdir(), 'plasmidlab-parse-'))
const entry = join(work, 'entry.ts')
writeFileSync(entry, `
import { openFiles } from ${JSON.stringify(join(core, 'io'))}
import { toFasta, toGenBank } from ${JSON.stringify(join(core, 'genbank'))}
import { isAbif, isScf } from ${JSON.stringify(join(core, 'trace'))}
import { rangeLength } from ${JSON.stringify(join(core, 'seq'))}
import type { SeqDoc } from ${JSON.stringify(join(core, 'types'))}

/**
 * What the viewer page prints, derived from the doc the app's reader returned. Coordinates are 1-based and
 * inclusive, as a GenBank file writes them; \`segments\` keeps the app's 0-based ranges for the map drawing,
 * where a segment with end < start wraps the origin of a circle. \`strand\` is the .dna directionality:
 * 0 none, 1 forward, 2 reverse, 3 both.
 */
function summary(doc: SeqDoc) {
  const n = doc.seq.length
  const features = doc.features.map((f) => {
    const segs = f.segments.length ? f.segments : [{ start: 0, end: n ? n - 1 : 0 }]
    return {
      name: f.name,
      type: f.type,
      start: segs[0].start + 1,
      end: segs[segs.length - 1].end + 1,
      bp: segs.reduce((t, s) => t + rangeLength(s, n), 0),
      strand: f.directionality,
      segments: segs.map((s) => ({ start: s.start, end: s.end, color: s.color })),
    }
  })
  features.sort((a, b) => a.start - b.start || a.end - b.end)
  return { name: doc.name, length: n, circular: doc.circular, features }
}

;(globalThis as any).PlasmidParse = { openFiles, summary, toGenBank, toFasta, isAbif, isScf }
`)
const out = join(work, 'parse.js')
execFileSync(esbuild, [entry, '--bundle', '--format=iife', '--target=es2020', '--minify', '--legal-comments=none', `--outfile=${out}`], { stdio: 'inherit' })
const body = readFileSync(out, 'utf8')
for (const must of ['openFiles', 'summary', 'toGenBank', 'toFasta', 'isAbif', 'isScf']) {
  if (!body.includes(must)) throw new Error(`bundle lost ${must}; check the app's exports`)
}
writeFileSync(join(site, 'assets', 'parse.js'), `// Generated by tools/build-parse.mjs from the PlasmidLab app (app/src/core). Do not edit by hand.
// openFiles: the app's own readers for .dna, GenBank, EMBL and FASTA (app/src/core/io.ts), with the SnapGene
// XML and xz code they need. toGenBank + toFasta: the app's writers. summary: the fields the viewer page prints.
${body}`)
rmSync(work, { recursive: true, force: true })
console.log(`assets/parse.js: ${(body.length / 1024).toFixed(1)} kB from ${core}`)

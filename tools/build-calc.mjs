// Regenerates assets/calc.js from the app's own code, so the website and the app give the same numbers.
// Usage: node tools/build-calc.mjs [path/to/plasmidlab/app]   (default: ../plasmidlab/app)
import { mkdtempSync, writeFileSync, rmSync, readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { tmpdir } from 'node:os'

const site = join(dirname(fileURLToPath(import.meta.url)), '..')
const app = resolve(process.argv[2] ?? join(site, '..', 'plasmidlab', 'app'))
const esbuild = join(app, 'node_modules', '.bin', 'esbuild')
const core = join(app, 'src', 'core')

const work = mkdtempSync(join(tmpdir(), 'plasmidlab-calc-'))
const entry = join(work, 'entry.ts')
writeFileSync(entry, `
import { meltingTemp } from ${JSON.stringify(join(core, 'seq'))}
import { fragments } from ${JSON.stringify(join(core, 'enzymes'))}
import { migration, SUPERCOILED } from ${JSON.stringify(join(core, 'gel'))}
import { LADDERS } from ${JSON.stringify(join(core, 'reference'))}
// Only the lengths: the site does not print a supplier's product name.
const ladders = LADDERS.filter((l) => /^(1 kb|100 bp) DNA Ladder$/.test(l.name)).map((l) => ({
  name: l.name.replace(' DNA Ladder', ' ladder'),
  units: l.units,
  lengths: l.fragments.filter((f) => f.format !== 'hidden').map((f) => f.length),
}))
;(globalThis as any).PlasmidCalc = { meltingTemp, fragments, migration, SUPERCOILED, ladders }
`)
const out = join(work, 'calc.js')
execFileSync(esbuild, [entry, '--bundle', '--format=iife', '--target=es2020', '--legal-comments=none', `--outfile=${out}`], { stdio: 'inherit' })
const body = readFileSync(out, 'utf8')
for (const must of ['meltingTemp', 'fragments', 'migration', 'SUPERCOILED', 'ladders']) {
  if (!body.includes(must)) throw new Error(`bundle lost ${must}; check the app's exports`)
}
writeFileSync(join(site, 'assets', 'calc.js'), `// Generated by tools/build-calc.mjs from the PlasmidLab app (app/src/core). Do not edit by hand.
// meltingTemp: SantaLucia 1998 nearest neighbour. fragments + migration + ladders: the app's gel code.
${body}`)
rmSync(work, { recursive: true, force: true })
console.log(`assets/calc.js: ${(body.length / 1024).toFixed(1)} kB from ${core}`)
